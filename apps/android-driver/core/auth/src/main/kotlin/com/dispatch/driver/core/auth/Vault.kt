package com.dispatch.driver.core.auth

import android.annotation.SuppressLint
import android.content.SharedPreferences
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import java.io.IOException
import java.security.KeyStore
import java.util.Base64
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

@Serializable
data class SignedIn(val accessToken: String, val subject: String, val expiresAtEpochMs: Long)

/** Everything sign-in keeps between launches. */
@Serializable
data class AuthRecord(val session: SignedIn? = null, val pending: PendingSignIn? = null)

interface Vault {
    fun read(): AuthRecord

    /** Throws [IOException] when [record] could not be stored. */
    fun write(record: AuthRecord)
}

interface Sealer {
    fun seal(plain: ByteArray): ByteArray

    /** Throws when [sealed] was not sealed by this key, or was altered. */
    fun open(sealed: ByteArray): ByteArray
}

/** AES-256-GCM; the nonce, generated by the cipher, is prefixed to the ciphertext. */
class AesGcmSealer(private val key: SecretKey) : Sealer {

    override fun seal(plain: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION).apply { init(Cipher.ENCRYPT_MODE, key) }
        val nonce = cipher.iv
        return byteArrayOf(nonce.size.toByte()) + nonce + cipher.doFinal(plain)
    }

    override fun open(sealed: ByteArray): ByteArray {
        val nonceSize = sealed[0].toInt()
        val cipher = Cipher.getInstance(TRANSFORMATION)
            .apply { init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(TAG_BITS, sealed, 1, nonceSize)) }
        return cipher.doFinal(sealed, 1 + nonceSize, sealed.size - 1 - nonceSize)
    }

    companion object {
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val TAG_BITS = 128

        /**
         * Section 23.1's Keystore-backed storage: the key never leaves the
         * Keystore, and is made on first use.
         */
        fun keystore(alias: String = "dispatch-auth"): AesGcmSealer {
            val store = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
            val key = store.getKey(alias, null) as SecretKey?
                ?: KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, "AndroidKeyStore").apply {
                    init(
                        KeyGenParameterSpec.Builder(alias, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
                            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                            .setKeySize(256)
                            .build(),
                    )
                }.generateKey()
            return AesGcmSealer(key)
        }
    }
}

/**
 * The record, sealed, in app-private preferences (excluded from backup by the
 * manifest). One that no longer opens — the key was lost — reads as signed out.
 */
class SealedPrefsVault(private val prefs: SharedPreferences, private val sealer: Sealer) : Vault {

    override fun read(): AuthRecord =
        prefs.getString(KEY, null)
            ?.let { runCatching { json.decodeFromString(AuthRecord.serializer(), sealer.open(Base64.getDecoder().decode(it)).decodeToString()) }.getOrNull() }
            ?: AuthRecord()

    // commit, not apply: a session that is not on disk would be lost to a
    // process death between here and the next launch.
    @SuppressLint("ApplySharedPref")
    override fun write(record: AuthRecord) {
        val sealed = Base64.getEncoder().encodeToString(sealer.seal(json.encodeToString(AuthRecord.serializer(), record).encodeToByteArray()))
        if (!prefs.edit().putString(KEY, sealed).commit()) throw IOException("The sign-in record could not be stored.")
    }

    internal companion object {
        const val KEY = "record"
        private val json = Json { ignoreUnknownKeys = true }
    }
}
